#!/usr/bin/env python3
"""Aggregate ablation run reports into pooled statistics and a LaTeX table.

Usage:  python aggregate_results.py runs/
Reads:  runs/<dataset>_<mode>_seed<k>_final_report.json
Writes: runs/ablation_summary.md  and  runs/ablation_table.tex
        (paste ablation_table.tex into Section 7.3 of the paper)
"""
import glob
import json
import math
import os
import re
import sys
from collections import defaultdict


def _binom_cdf(k, n, p):
    if p <= 0.0:
        return 1.0
    if p >= 1.0:
        return 1.0 if k >= n else 0.0
    total, lp, lq = 0.0, math.log(p), math.log1p(-p)
    for i in range(0, k + 1):
        total += math.exp(math.lgamma(n + 1) - math.lgamma(i + 1) - math.lgamma(n - i + 1)
                          + i * lp + (n - i) * lq)
    return min(total, 1.0)


def clopper_pearson(x, n, alpha=0.05):
    if n == 0:
        return (0.0, 1.0)

    def _solve(fn, lo=0.0, hi=1.0, iters=200):
        for _ in range(iters):
            mid = (lo + hi) / 2
            lo, hi = (mid, hi) if fn(mid) else (lo, mid)
        return (lo + hi) / 2

    lower = 0.0 if x == 0 else _solve(lambda p: 1 - _binom_cdf(x - 1, n, p) <= alpha / 2)
    upper = 1.0 if x == n else 1.0 - _solve(lambda p: 1 - _binom_cdf(n - x - 1, n, p) <= alpha / 2)
    return (lower, upper)


MODE_LABELS = {
    "circular": "Circular (same-family LLM)",
    "reflexion": "Reflexion (same-family + self-critique)",
    "cross-only": "Cross-architecture LLM only",
    "rules-only": "Deterministic rules only",
    "hybrid": "Hybrid (rules + cross-architecture)",
    "hybrid-circular": "Hybrid (rules + same-family)",
}
MODE_ORDER = ["circular", "reflexion", "rules-only", "cross-only", "hybrid", "hybrid-circular"]


def main(outdir):
    pooled = defaultdict(lambda: {"tp": 0, "fp": 0, "fn": 0, "tn": 0, "seeds": set(),
                                  "seed_recalls": [], "unscored": 0})
    for f in glob.glob(os.path.join(outdir, "*_final_report.json")):
        base = os.path.basename(f)
        mm = re.match(r"(.+?)_([a-z\-]+)_seed(\d+)_final_report\.json", base)
        if not mm:
            continue
        dataset, mode, seed = mm.group(1), mm.group(2), int(mm.group(3))
        r = json.load(open(f))
        cm = r["checker_metrics"]
        key = (dataset, mode)
        for k in ("tp", "fp", "fn", "tn"):
            pooled[key][k] += cm[k]
        pooled[key]["seeds"].add(seed)
        if cm.get("recall") is not None:
            pooled[key]["seed_recalls"].append(cm["recall"])
        pooled[key]["unscored"] += r.get("verdict_coverage", {}).get("rows_missing_verdict", 0)

    if not pooled:
        print(f"No reports found in {outdir}/")
        return

    md = ["# Ablation summary (pooled across seeds)\n"]
    tex = [
        "% Auto-generated by aggregate_results.py — paste into the paper (Section 7.3).",
        "\\begin{table}[h]",
        "\\centering",
        "\\caption{Ablation: checker recall/precision against ground truth, pooled across seeds. CIs are exact Clopper--Pearson 95\\%.}",
        "\\label{tab:ablation}",
        "\\small",
        "\\begin{tabular}{llrlcrrr}",
        "\\toprule",
        "\\textbf{Dataset} & \\textbf{Configuration} & \\textbf{TP/Pos} & \\textbf{Recall (CI)} & \\textbf{Seed min--max} & \\textbf{FP} & \\textbf{Prec.} & \\textbf{Unsc.} \\\\",
        "\\midrule",
    ]
    for dataset in sorted({k[0] for k in pooled}):
        for mode in MODE_ORDER:
            key = (dataset, mode)
            if key not in pooled:
                continue
            d = pooled[key]
            tp, fp, fn, tn = d["tp"], d["fp"], d["fn"], d["tn"]
            pos, flagged, nseeds = tp + fn, tp + fp, len(d["seeds"])
            rec = tp / pos if pos else float("nan")
            prec = tp / flagged if flagged else float("nan")
            rci = clopper_pearson(tp, pos) if pos else (float("nan"),) * 2
            md.append(
                f"- **{dataset} / {MODE_LABELS.get(mode, mode)}** ({nseeds} seeds): "
                f"TP={tp} FN={fn} FP={fp} TN={tn} | recall {tp}/{pos}"
                + (f" = {rec:.3f} CI [{rci[0]:.3f}, {rci[1]:.3f}]" if pos else "")
                + (f" | precision {prec:.3f}" if flagged else " | nothing flagged")
                + (f" | unscored rows {d['unscored']}" if d["unscored"] else "")
            )
            srs = d["seed_recalls"]
            minmax = f"{min(srs):.2f}--{max(srs):.2f}" if srs else "--"
            tex.append(
                f"{dataset.replace(chr(95), chr(92)+chr(95))} & {MODE_LABELS.get(mode, mode)} & "
                + (f"{tp}/{pos}" if pos else "--")
                + " & "
                + (f"{rec:.3f} [{rci[0]:.3f}, {rci[1]:.3f}]" if pos else "--")
                + f" & {minmax} & {fp} & "
                + (f"{prec:.2f}" if flagged else "--")
                + f" & {d['unscored']} \\\\"
            )
        tex.append("\\midrule")
    tex[-1] = "\\bottomrule"
    tex += ["\\end{tabular}", "\\end{table}"]

    open(os.path.join(outdir, "ablation_summary.md"), "w").write("\n".join(md) + "\n")
    open(os.path.join(outdir, "ablation_table.tex"), "w").write("\n".join(tex) + "\n")
    print("\n".join(md))
    print(f"\nWrote {outdir}/ablation_summary.md and {outdir}/ablation_table.tex")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "runs")
